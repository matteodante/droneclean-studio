/**
 * Turns the contract snapshot's JSON Schemas into TypeScript types, so the editor's hand-written
 * `types.ts` can be compared with the cloud's contract by the compiler (`contract.test.ts`).
 *
 * Used by the test and by `checks/shadow-contract-snapshot.mjs` (Node strips the types; keep this
 * file to syntax Node can strip: no enums, no parameter properties). It reads only the JSON
 * Schema that zod 4's `toJSONSchema` writes for the cloud's schemas: objects, arrays, tuples,
 * records, string/number/boolean/null, enums and literals, and `anyOf` for a nullable value.
 * Anything else throws, so a cloud schema that the editor cannot compare is noticed when the
 * snapshot is made and not silently skipped.
 */

export interface JsonSchema {
  type?: string | string[]
  properties?: Record<string, JsonSchema>
  required?: string[]
  items?: JsonSchema | false
  prefixItems?: JsonSchema[]
  additionalProperties?: JsonSchema | boolean
  enum?: (string | number | boolean | null)[]
  const?: string | number | boolean | null
  anyOf?: JsonSchema[]
  [key: string]: unknown
}

function literal(value: string | number | boolean | null): string {
  return JSON.stringify(value)
}

function objectToType(schema: JsonSchema): string {
  const properties = schema.properties
  if (!properties) {
    const value = schema.additionalProperties
    if (value && typeof value === 'object') return `Record<string, ${schemaToType(value)}>`
    throw new Error('An object schema without properties or a value type is not supported.')
  }
  const required = new Set(schema.required ?? [])
  const lines = Object.entries(properties).map(
    ([name, member]) =>
      `${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${schemaToType(member)}`,
  )
  return `{ ${lines.join('; ')} }`
}

function arrayToType(schema: JsonSchema): string {
  if (schema.prefixItems) {
    return `[${schema.prefixItems.map((member) => schemaToType(member)).join(', ')}]`
  }
  if (!schema.items) throw new Error('An array schema without items is not supported.')
  return `(${schemaToType(schema.items)})[]`
}

/** The TypeScript type of one JSON Schema `type` keyword (not a list of them). */
function typedToType(schema: JsonSchema, type: string | undefined): string {
  switch (type) {
    case 'string':
    case 'boolean':
    case 'null':
      return type
    case 'number':
    case 'integer':
      return 'number'
    case 'array':
      return arrayToType(schema)
    case 'object':
      return objectToType(schema)
    default:
      throw new Error(`Unsupported JSON Schema: ${JSON.stringify(schema).slice(0, 200)}`)
  }
}

/** The TypeScript type of one JSON Schema, on one line. */
function schemaToType(schema: JsonSchema): string {
  if (schema.const !== undefined) return literal(schema.const)
  if (schema.enum) return schema.enum.map(literal).join(' | ')
  if (schema.anyOf) return schema.anyOf.map((member) => schemaToType(member)).join(' | ')
  // `{ type: ['string', 'null'] }`: a nullable primitive.
  const types = Array.isArray(schema.type) ? schema.type : [schema.type]
  return types.map((type) => typedToType(schema, type)).join(' | ')
}

/**
 * The snapshot's form of what zod wrote: no `$schema`; no regular expression beside
 * `format: 'date-time'` or `'uuid'` (the format says the same and the snapshot stays readable);
 * and every object closed. zod closes the objects of an answer (`additionalProperties: false`) and
 * leaves those of a request open, because the API silently drops a request's unknown keys; a key
 * the cloud does not know is a mistake in the editor, never something the cloud keeps.
 */
export function snapshotForm(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(snapshotForm)
  if (node === null || typeof node !== 'object') return node
  const source = node as Record<string, unknown>
  const copy: Record<string, unknown> = {}
  for (const [key, value] of Object.entries(source)) {
    const dropped =
      key === '$schema' ||
      (key === 'pattern' && ['date-time', 'uuid'].includes(String(source.format)))
    if (!dropped) copy[key] = snapshotForm(value)
  }
  if (copy.type === 'object' && copy.properties) copy.additionalProperties = false
  return copy
}

/** The whole generated file: one exported type per snapshot entry, in the snapshot's order. */
export function snapshotToTypesFile(
  header: { contract: number; cloudCommit: string },
  entries: Record<string, JsonSchema>,
): string {
  const lines = [
    '// Generated by `checks/shadow-contract-snapshot.mjs` from `contract-snapshot.json`: do not edit.',
    `// The cloud's contract ${header.contract}, as written by its zod schemas at ${header.cloudCommit}.`,
    '',
  ]
  for (const [name, schema] of Object.entries(entries)) {
    // One line each, and the formatter leaves it so: the test compares this text with the file.
    lines.push('// prettier-ignore', `export type Contract${name} = ${schemaToType(schema)}`)
  }
  return `${lines.join('\n')}\n`
}
